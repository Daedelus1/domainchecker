package clientmanager

import (
	"errors"
	"fmt"
	"log/slog"
	"slices"
	"sync"
	"time"

	"ethanstewart.net/domainchecker/shared"
	"ethanstewart.net/domainchecker/shared/websocketclient"
	"github.com/gorilla/websocket"
)

const (
	HEARTBEAT_INTERVAL = time.Second * 3
)

type ClientManager struct {
	clientIDs         []shared.ClientID
	clients           map[shared.ClientID]*websocketclient.Client
	mu                *sync.RWMutex
	inboundMsgs       chan shared.InboundMessage
	ResponseChan      chan shared.UrlResponse
	heartbeatMu       *sync.Mutex
	dispatchMu        *sync.Mutex
	shutdownRegisters chan struct{}
}

// NewClientManager constructs an empty, ready-to-use ClientManager. The
// heartbeat and dispatch loops aren't started here; AddClient starts them
// lazily on the first connection.
func NewClientManager() *ClientManager {
	return &ClientManager{
		clientIDs:         make([]shared.ClientID, 0),
		clients:           make(map[shared.ClientID]*websocketclient.Client),
		mu:                &sync.RWMutex{},
		inboundMsgs:       make(chan shared.InboundMessage),
		ResponseChan:      make(chan shared.UrlResponse, 10),
		heartbeatMu:       &sync.Mutex{},
		dispatchMu:        &sync.Mutex{},
		shutdownRegisters: make(chan struct{}),
	}
}

// SendJSON sends msg to whichever connected client happens to be first in
// clientIDs; there's no other basis for the choice, so this is only useful
// when the specific recipient doesn't matter. Returns an error if no client
// is connected. Most callers want SendJSONToClient instead.
func (c *ClientManager) SendJSON(msg any) (bool, error) {
	c.mu.RLock()
	defer c.mu.RUnlock()

	clientId, ok := c.getFirstClientLocked()
	if !ok {
		return false, errors.New("cannot send JSON to client. No clients are connected")
	}

	err := c.sendJSONToClientLocked(clientId, msg)
	if err != nil {
		return false, err
	}
	return true, nil
}

// Responses returns the channel UrlResponses from any connected client are
// published to, via dispatch. RequestRegistry reads from it through the
// clientDispatcher interface rather than touching ResponseChan directly.
func (c *ClientManager) Responses() chan shared.UrlResponse {
	return c.ResponseChan
}

// ClientLastSeen returns the last time id was seen (see
// updateClientLastSeen), or false if id isn't registered.
func (c *ClientManager) ClientLastSeen(id shared.ClientID) (time.Time, bool) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	client, exists := c.clients[id]
	if !exists {
		return time.Time{}, false
	}
	return client.LastSeen, true
}

// Close closes every connected client and blocks until all of their
// cleanup callbacks have run. Must be called at most once: it closes
// inboundMsgs and ResponseChan unconditionally, so a second call panics.
func (c *ClientManager) Close() {
	c.mu.Lock()
	// Snapshotted so the lock isn't held while waiting on client shutdown below.
	ids := make([]shared.ClientID, len(c.clientIDs))
	copy(ids, c.clientIDs)

	close(c.inboundMsgs)
	close(c.ResponseChan)
	c.mu.Unlock()

	var wg sync.WaitGroup
	for _, id := range ids {
		wg.Add(1)
		go func(id shared.ClientID) {
			defer wg.Done()
			_ = c.RemoveClient(id)
		}(id)
	}
	wg.Wait()
}

// AddClient registers an already-upgraded websocket connection as a new
// client and begins servicing it. Lazily starts the shared heartbeat and
// dispatch goroutines on the first call; later calls reuse them, since
// heartbeatMu/dispatchMu make the lazy start idempotent. The returned ID is
// generated by websocketclient.NewClient, which is responsible for making
// it distinct from every ID already in clientIDs.
func (c *ClientManager) AddClient(conn *websocket.Conn) shared.ClientID {
	c.mu.Lock()
	defer c.mu.Unlock()

	client := websocketclient.NewClient(c.clientIDs, conn, func(im shared.InboundMessage) {
		c.inboundMsgs <- im
	}, func(id shared.ClientID) {
		slog.Info("Cleanup triggered for client", "id", id.ToString())
	})
	id := client.Id

	if c.heartbeatMu.TryLock() {
		c.heartbeatMu.Unlock()
		go c.handleHeartbeat()
	}

	if c.dispatchMu.TryLock() {
		c.dispatchMu.Unlock()
		go c.dispatch()
	}

	c.clients[id] = client
	c.clientIDs = append(c.clientIDs, id)

	slog.Info("Client connected", "id", client.Id.ToString())
	client.Start()
	return id
}

// RemoveClient unregisters id and tears down its connection. Returns an
// error if id isn't currently registered. Releases mu before calling
// client.Close(), since Close synchronously invokes the client's onClose
// callback, and that callback must never re-enter ClientManager state while
// mu is still held.
func (c *ClientManager) RemoveClient(id shared.ClientID) error {
	c.mu.Lock()
	client, exists := c.clients[id]
	if !exists {
		c.mu.Unlock()
		return fmt.Errorf("cannot remove client with id %s, client does not exist", id.ToString())
	}

	delete(c.clients, id)
	c.clientIDs = slices.DeleteFunc(c.clientIDs, func(e shared.ClientID) bool {
		return e == id
	})
	c.mu.Unlock()

	client.Close()
	return nil
}

// updateClientLastSeen records that id was just seen, for clientIsTimedOut
// to measure against. No-ops if id is unknown (e.g. already removed).
func (c *ClientManager) updateClientLastSeen(id shared.ClientID) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.updateClientLastSeenLocked(id)
}

// updateClientLastSeenLocked is updateClientLastSeen for a caller that
// already holds mu.
func (c *ClientManager) updateClientLastSeenLocked(id shared.ClientID) {
	if client, ok := c.clients[id]; ok {
		client.LastSeen = time.Now()
	}
}

// clientIsTimedOut reports whether id has gone silent for longer than
// websocketclient.TIMEOUT_DURATION. Returns an error if id isn't
// registered.
func (c *ClientManager) clientIsTimedOut(id shared.ClientID) (bool, error) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.clientIsTimedOutLocked(id)
}

// clientIsTimedOutLocked is clientIsTimedOut for a caller that already
// holds at least a read lock on mu.
func (c *ClientManager) clientIsTimedOutLocked(id shared.ClientID) (bool, error) {
	client, exists := c.clients[id]
	if !exists {
		return false, fmt.Errorf("unrecognized client: %s", id.ToString())
	}
	return time.Since(client.LastSeen) > websocketclient.TIMEOUT_DURATION, nil
}

// sendHeartbeatToClient sends a single heartbeat to id. Returns an error if
// id isn't registered or the write fails; handleHeartbeat treats either as
// grounds to remove the client.
func (c *ClientManager) sendHeartbeatToClient(id shared.ClientID) error {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.sendJSONToClientLocked(id, shared.Heartbeat{})
}

// SendJSONToClient sends msg to a specific, already-known client. Returns
// an error if clientID isn't registered or the write fails.
func (c *ClientManager) SendJSONToClient(clientID shared.ClientID, msg any) error {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.sendJSONToClientLocked(clientID, msg)
}

// sendJSONToClientLocked is SendJSONToClient for a caller that already
// holds at least a read lock on mu.
func (c *ClientManager) sendJSONToClientLocked(clientID shared.ClientID, msg any) error {
	client, exists := c.clients[clientID]
	if !exists {
		return errors.New("cannot send JSON to client. Client does not exist")
	}
	return client.SendJSON(msg)
}

// handleHeartbeat runs for as long as at least one client is connected,
// pinging every currently-connected client once per HEARTBEAT_INTERVAL and
// removing any that have gone silent past the timeout or whose heartbeat
// send itself failed. Exits as soon as the client list is observed empty;
// AddClient relaunches it on the next connection. heartbeatMu ensures only
// one instance ever runs at a time, so this must only be started via
// AddClient's TryLock check, not called directly.
func (c *ClientManager) handleHeartbeat() {
	c.heartbeatMu.Lock()
	defer c.heartbeatMu.Unlock()

	ticker := time.NewTicker(HEARTBEAT_INTERVAL)
	defer ticker.Stop()

	var ids []shared.ClientID
	capacity := 0

	clientsToPing := make(chan shared.ClientID)
	defer close(clientsToPing)

	go func(clientsToPing chan shared.ClientID) {
		for client := range clientsToPing {
			err := c.sendHeartbeatToClient(client)
			if err != nil {
				_ = c.RemoveClient(client)
			}
		}
	}(clientsToPing)

	for range ticker.C {
		c.mu.RLock()
		numIds := len(c.clientIDs)
		if numIds == 0 {
			c.mu.RUnlock()
			return
		}
		if numIds > capacity {
			capacity = numIds + 5
			ids = make([]shared.ClientID, capacity)
		}
		copy(ids, c.clientIDs)
		c.mu.RUnlock()

		for _, id := range ids[:numIds] {
			clientsToPing <- id

			if timedOut, _ := c.clientIsTimedOut(id); timedOut {
				_ = c.RemoveClient(id)
			}
		}
	}
}

// GetFirstClient returns an arbitrary currently-connected client ID
// (whichever happens to be at index 0 of clientIDs), or false if none are
// connected.
func (c *ClientManager) GetFirstClient() (shared.ClientID, bool) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	return c.getFirstClientLocked()
}

// getFirstClientLocked is GetFirstClient for a caller that already holds at
// least a read lock on mu. Returns a non-nil zero-value ClientID alongside
// false when no client is connected, so callers must check the bool rather
// than the ID.
func (c *ClientManager) getFirstClientLocked() (shared.ClientID, bool) {
	if len(c.clientIDs) == 0 {
		return shared.ClientID(time.Now()), false
	}
	return c.clientIDs[0], true
}

// dispatch runs once started (via AddClient, guarded by dispatchMu so only
// one instance is ever active) and consumes every inbound message from
// every connected client until inboundMsgs is closed. A heartbeat reply
// updates the sender's LastSeen; a UrlResponse is forwarded to
// ResponseChan; anything else is logged and dropped.
func (c *ClientManager) dispatch() {
	c.dispatchMu.Lock()
	defer c.dispatchMu.Unlock()
	for msg := range c.inboundMsgs {
		switch v := shared.ParseBinaryIntoMessageTypes(msg.Msg).(type) {
		case shared.Heartbeat:
			slog.Debug("received heartbeat reply", "id", msg.Id.ToString())
			c.updateClientLastSeen(msg.Id)
		case shared.UrlResponse:
			c.ResponseChan <- v
		case shared.UrlRequest:
			slog.Warn("Unexpected Request from client", "Request", v)
		case []byte:
			slog.Warn("Unexpected JSON: ", "msg", string(v))
		}
	}
}
